def t(key: str, **kwargs) -> str:
    """Look up a string by key and apply ``str.format`` substitutions."""
    template = M.get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template